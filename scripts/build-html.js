// Generates the language versions of the page from src/index.template.html and src/i18n/<lang>.json
// (run via `npm run build`, which also builds the CSS and adds cache-busting hashes)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const template = fs.readFileSync(path.join(root, 'src/index.template.html'), 'utf8');

const languages = [
    { lang: 'cs', label: 'CS', url: 'https://dev.goffa.cz/', home: '/', output: 'index.html', ogLocale: 'cs_CZ', ogImagePath: '/assets/images/og-image.png' },
    { lang: 'en', label: 'EN', url: 'https://dev.goffa.cz/en/', home: '/en/', output: 'en/index.html', ogLocale: 'en_US', ogImagePath: '/assets/images/og-image-en.png' }
];

// The switcher is rendered here, so its classes are listed in tailwind.config.js content
function languageSwitcher(current) {
    return languages.map(language => language.lang === current.lang
        ? `<span class="px-2.5 py-1 rounded-full bg-primary text-white" aria-current="page">${language.label}</span>`
        : `<a href="${language.home}" hreflang="${language.lang}" lang="${language.lang}" class="px-2.5 py-1 rounded-full text-gray-400 hover:text-white transition-colors">${language.label}</a>`
    ).join('\n                    ');
}

for (const language of languages) {
    const texts = JSON.parse(fs.readFileSync(path.join(root, `src/i18n/${language.lang}.json`), 'utf8'));
    const values = {
        ...texts,
        generatedNotice: `<!-- Generated from src/index.template.html and src/i18n/${language.lang}.json by \`npm run build\` – do not edit this file directly -->`,
        languageSwitcher: languageSwitcher(language),
        'meta.lang': language.lang,
        'meta.url': language.url,
        'meta.home': language.home,
        'meta.ogLocale': language.ogLocale,
        'meta.ogLocaleAlternate': languages.find(other => other !== language).ogLocale,
        'meta.ogImagePath': language.ogImagePath
    };

    const html = template.replace(/\{\{([\w.]+)\}\}/g, (placeholder, key) => {
        if (!(key in values)) {
            throw new Error(`Missing text "${key}" in src/i18n/${language.lang}.json`);
        }
        return values[key];
    });

    const outputPath = path.join(root, language.output);
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, html);
}
